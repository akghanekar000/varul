import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
import { aiChatSchema, buildPlannerReply, getAiSetupGuide } from './lib/ai';

dotenv.config();

const app = express();
const port = Number(process.env.PORT || 3001);

app.use(cors());
app.use(express.json({ limit: '1mb' }));

app.get('/api/health', (_req, res) => {
  res.json({
    ok: true,
    service: 'devmind-ai-api',
    status: 'healthy',
    ai: getAiSetupGuide()
  });
});

app.get('/api/models', (_req, res) => {
  res.json({
    providers: getAiSetupGuide().providers,
    defaultProvider: process.env.AI_PROVIDER || 'openai'
  });
});

app.post('/api/ai/chat', async (req, res) => {
  const parsed = aiChatSchema.safeParse(req.body);

  if (!parsed.success) {
    return res.status(400).json({
      error: 'Invalid request',
      details: parsed.error.flatten()
    });
  }

  const { message } = parsed.data;
  const providerStatus = getAiSetupGuide();

  if (providerStatus.status === 'missing') {
    return res.status(200).json({
      status: 'config-required',
      provider: 'none',
      model: null,
      reply: 'AI provider configuration is required. Add environment variables before enabling live model calls.',
      setup: providerStatus,
      fallback: buildPlannerReply(message)
    });
  }

  const providerName = (process.env.AI_PROVIDER || 'openai').toLowerCase();
  const apiKey = process.env[`${providerName.toUpperCase()}_API_KEY`];

  if (!apiKey) {
    return res.status(200).json({
      status: 'config-required',
      provider: providerName,
      model: process.env.OPENAI_MODEL || 'default',
      reply: `The ${providerName} provider is selected, but its API key is not configured on the server.`,
      setup: providerStatus,
      fallback: buildPlannerReply(message)
    });
  }

  try {
    const endpoint = providerName === 'openai'
      ? 'https://api.openai.com/v1/chat/completions'
      : providerName === 'anthropic'
        ? 'https://api.anthropic.com/v1/messages'
        : 'https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent';

    const headers: Record<string, string> = {
      'Content-Type': 'application/json'
    };

    let payload: Record<string, unknown>;

    if (providerName === 'openai') {
      headers.Authorization = `Bearer ${apiKey}`;
      payload = {
        model: process.env.OPENAI_MODEL || 'gpt-4o-mini',
        messages: [{ role: 'user', content: message }],
        temperature: 0.2
      };
    } else if (providerName === 'anthropic') {
      headers['x-api-key'] = apiKey;
      headers['anthropic-version'] = '2023-06-01';
      payload = {
        model: process.env.ANTHROPIC_MODEL || 'claude-3-5-sonnet-20241022',
        max_tokens: 800,
        messages: [{ role: 'user', content: message }]
      };
    } else {
      payload = {
        contents: [{ parts: [{ text: message }] }],
        generationConfig: { temperature: 0.2, maxOutputTokens: 800 }
      };
      headers['x-goog-api-key'] = apiKey;
    }

    const response = await fetch(endpoint, {
      method: 'POST',
      headers,
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      const errorBody = await response.text();
      return res.status(502).json({
        status: 'provider-error',
        provider: providerName,
        error: 'Provider returned an error.',
        details: errorBody,
        fallback: buildPlannerReply(message)
      });
    }

    const body = await response.json();
    const reply = providerName === 'openai'
      ? body.choices?.[0]?.message?.content
      : providerName === 'anthropic'
        ? body.content?.[0]?.text
        : body.candidates?.[0]?.content?.parts?.[0]?.text;

    return res.json({
      status: 'ok',
      provider: providerName,
      model: providerName === 'google' ? (process.env.GOOGLE_MODEL || 'gemini-1.5-flash') : process.env[`${providerName.toUpperCase()}_MODEL`] || 'default',
      reply: reply || 'No reply generated by the provider.',
      usage: body.usage || null
    });
  } catch (error) {
    return res.status(500).json({
      status: 'runtime-error',
      provider: providerName,
      error: error instanceof Error ? error.message : 'Unknown error',
      fallback: buildPlannerReply(message)
    });
  }
});

app.listen(port, () => {
  console.log(`DevMind AI API listening on http://localhost:${port}`);
});
